import re, unicodedata
def l1(s: str) -> str:
    s = unicodedata.normalize("NFKC", s).replace("\u3000", " ").replace("\u200b", "")
    s = re.sub(r"\s+", " ", s).strip()
    s = re.sub(r"[A-G]\s*调", "", s)
    s = re.sub(r"(?<=\S)\s*调$", "", s)
    s = re.sub(r"第\d+代", "", s)
    s = re.sub(r"(?<=[\u4e00-\u9fa5])\d$", "", s)
    s = re.sub(r"\s*[-—]\s*", "", s)
    return s.strip()

